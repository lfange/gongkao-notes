def plans():
    result = []
    for i, topics in enumerate(TOPICS):
        day = START + timedelta(days=i)
        minutes = [100, 65, 65, 10]
        if i in (19, 23, 26, 29):
            minutes = [120, 55, 55, 10]
        elif i in (20, 24, 27):
            minutes = [40, 150, 40, 10]
        elif i in (21, 25, 28):
            minutes = [55, 55, 120, 10]
        result.append(dict(day=i+1, date=day.isoformat(), tasks=[
            dict(subject=s, minutes=m, task=t)
            for s, m, t in zip(('行测','申论（行政执法类）','公安专业科目','心理素质测试准备'), minutes, topics)
        ]))
    return result

def task_table(plan):
    lines = ['| 科目 | 时间 | 学习与做题任务 |','| --- | --- | --- |']
    for task in plan['tasks']:
        lines.append(f"| {task['subject']} | {task['minutes']}分钟 | {task['task']} |")
    return '\n'.join(lines)

